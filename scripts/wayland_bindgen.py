def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("xml", nargs="+", help="protocol XML file(s); first must be core wayland.xml")
    ap.add_argument("--out", default="wayland", help="output package dir")
    args = ap.parse_args()

    core = parse_protocol(args.xml[0])
    extras = [parse_protocol(p) for p in args.xml[1:]]

    out = args.out
    os.makedirs(out, exist_ok=True)
    os.makedirs(os.path.join(out, "gen"), exist_ok=True)
    with open(os.path.join(out, "core.mojo"), "w") as f:
        f.write(CORE_HEADER + WRAPPER_DEFS + ARGUMENT_UNION)
    with open(os.path.join(out, "gen", f"{core.name}.mojo"), "w") as f:
        f.write(emit_interface_module(core))
    for extra in extras:
        with open(os.path.join(out, "gen", f"{extra.name}.mojo"), "w") as f:
            f.write(emit_interface_module(extra))
    print(f"wrote {out}/core.mojo + {len(extras)+1} protocol module(s)")
    # __init__.mojo files: package + gen subpackage
    with open(os.path.join(out, "gen", "__init__.mojo"), "w") as f:
        f.write("# AUTO-GENERATED — DO NOT EDIT.\n")
    init_lines = ["from wayland.core import *"]
    for extra in [core] + extras:
        init_lines.append(f"from wayland.gen.{extra.name} import *")
    with open(os.path.join(out, "__init__.mojo"), "w") as f:
        f.write("\n".join(init_lines) + "\n")


if __name__ == "__main__":
    main()