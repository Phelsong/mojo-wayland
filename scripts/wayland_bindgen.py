MOJO_PTR = "UnsafePointer[NoneType, MutAnyOrigin]"

# (xml type, interface attr present?) -> (mojo type, wl_argument tag)
# wl_argument tags: i(int) u(uint) f(fixed) s(string) o(object) n(new_id) a(array) h(fd)
